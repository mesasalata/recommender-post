def is_algorithm_result(value: object) -> bool:
    """Return whether a value resembles the current result schema."""
    return (
        isinstance(value, dict)
        and isinstance(value.get("rating"), dict)
        and isinstance(value.get("ranking"), dict)
        and isinstance(value.get("timing"), dict)
    )


def load_results(path: str | Path) -> dict[str, dict[str, object]]:
    """Load current-format algorithm results from a file or directory."""
    source = Path(path)

    if source.is_file():
        files = [source]
    elif source.is_dir():
        preferred = source / "results.json"
        files = [preferred] if preferred.exists() else sorted(
            source.glob("*.json")
        )
    else:
        return {}

    results: dict[str, dict[str, object]] = {}

    for filename in files:
        try:
            with filename.open(encoding="utf-8") as file:
                payload = json.load(file)
        except (OSError, json.JSONDecodeError) as error:
            print(f"  Skipping {filename}: {error}")
            continue

        if not isinstance(payload, dict):
            continue

        if is_algorithm_result(payload):
            name = payload.get("rating", {}).get("name")
            if isinstance(name, str):
                if name in results:
                    raise ValueError(
                        f"Duplicate result for algorithm {name!r}."
                    )
                results[name] = payload
            continue

        for name, value in payload.items():
            if isinstance(name, str) and is_algorithm_result(value):
                if name in results:
                    raise ValueError(
                        f"Duplicate result for algorithm {name!r}."
                    )
                results[name] = value

    return results


def algorithm_color(name: str) -> str:
    """Return the configured color for an algorithm."""
    return ALGORITHM_DISPLAY.get(name, (name, "#888888"))[1]


def algorithm_label(name: str) -> str:
    """Return the configured short display name for an algorithm."""
    return ALGORITHM_DISPLAY.get(name, (name, "#888888"))[0]


def nested_metric(
    result: dict[str, object],
    section: str,
    key: str,
) -> float | None:
    """Read a finite numeric value from a nested result section."""
    values = result.get(section)
    if not isinstance(values, dict):
        return None

    value = values.get(key)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None

    numeric = float(value)
    return numeric if np.isfinite(numeric) else None


def common_ranking_k(
    results: dict[str, dict[str, object]],
    algorithms: list[str],
) -> int:
    """Return the common ranking cutoff or reject inconsistent results."""
    values: set[int] = set()

    for name in algorithms:
        ranking = results[name].get("ranking")
        if not isinstance(ranking, dict):
            raise ValueError(f"{name} has no ranking result section.")

        raw_k = ranking.get("k")
        if isinstance(raw_k, bool) or not isinstance(raw_k, int):
            raise ValueError(f"{name} has an invalid ranking cutoff.")
        if raw_k <= 0:
            raise ValueError(f"{name} has a nonpositive ranking cutoff.")
        values.add(raw_k)

    if len(values) != 1:
        raise ValueError(
            "Algorithms use inconsistent ranking cutoffs: "
            f"{sorted(values)}."
        )
    return values.pop()


def ordered_algorithms(
    results: dict[str, dict[str, object]],
    required: tuple[str, str] | None = None,
) -> list[str]:
    """Return known algorithms in the canonical display order."""
    names: list[str] = []

    for name in ALGORITHM_ORDER:
        if name not in results:
            continue
        if required is not None:
            section, key = required
            if nested_metric(results[name], section, key) is None:
                continue
        names.append(name)

    # Preserve unexpected future algorithms after the canonical entries.
    for name in results:
        if name in names:
            continue
        if required is not None:
            section, key = required
            if nested_metric(results[name], section, key) is None:
                continue
        names.append(name)

    return names


def save_figure(
    figure: matplotlib.figure.Figure,
    output_path: Path,
    output_format: str,
) -> None:
    """Save and close a figure."""
    options: dict[str, object] = {
        "facecolor": "white",
        "bbox_inches": "tight",
        "pad_inches": 0.15,
    }
    if output_format == "png":
        options["dpi"] = 600

    figure.savefig(output_path, format=output_format, **options)
    plt.close(figure)
    print(f"  Saved: {output_path}")


def _save_figure_to_all(
    figure: matplotlib.figure.Figure,
    output_paths: list[Path],
    output_format: str,
) -> None:
    """Save one figure to several paths, then close it once."""
    options: dict[str, object] = {
        "facecolor": "white",
        "bbox_inches": "tight",
        "pad_inches": 0.15,
    }
    if output_format == "png":
        options["dpi"] = 600

    for output_path in output_paths:
        figure.savefig(output_path, format=output_format, **options)
        print(f"  Saved: {output_path}")
    plt.close(figure)


def add_vertical_value_labels(
    axis: plt.Axes,
    bars: object,
    values: list[float],
    precision: int = 4,
) -> None:
    """Add labels above vertical bars."""
    maximum = max(values, default=0.0)
    offset = maximum * 0.025 if maximum > 0 else 0.01

    for bar, value in zip(bars, values):
        axis.text(
            bar.get_x() + bar.get_width() / 2,
            value + offset,
            f"{value:.{precision}f}",
            ha="center",
            va="bottom",
            fontsize=9,
            fontweight="bold",
        )


def build_rating_errors(
    results: dict[str, dict[str, object]],
) -> matplotlib.figure.Figure | None:
    """Build raw and bounded RMSE/MAE comparisons."""
    algorithms = ordered_algorithms(results, ("rating", "rmse"))
    algorithms = [
        name
        for name in algorithms
        if all(
            nested_metric(results[name], "rating", key) is not None
            for key in ("mae", "bounded_rmse", "bounded_mae")
        )
    ]

    if not algorithms:
        print("  No complete rating-error data to plot.")
        return None

    labels = [algorithm_label(name) for name in algorithms]
    colors = [algorithm_color(name) for name in algorithms]
    x_values = np.arange(len(algorithms))

    chart_specs = [
        ("rmse", "Raw RMSE", "Lower is better"),
        ("mae", "Raw MAE", "Lower is better"),
        (
            "bounded_rmse",
            "Bounded RMSE",
            "Predictions clipped to the valid rating range",
        ),
        (
            "bounded_mae",
            "Bounded MAE",
            "Predictions clipped to the valid rating range",
        ),
    ]

    figure, axes = plt.subplots(2, 2, figsize=(17, 11))
    flat_axes = axes.ravel()

    for axis, (key, title, subtitle) in zip(flat_axes, chart_specs):
        values = [
            float(nested_metric(results[name], "rating", key))
            for name in algorithms
        ]
        bars = axis.bar(
            x_values,
            values,
            width=0.68,
            color=colors,
            edgecolor="white",
            linewidth=0.8,
        )
        axis.set_xticks(x_values)
        axis.set_xticklabels(labels, rotation=30, ha="right")
        axis.set_ylabel(key.replace("_", " ").upper())
        axis.set_title(f"{title}\n{subtitle}")
        maximum = max(values)
        axis.set_ylim(0, maximum * 1.18 if maximum > 0 else 1)
        add_vertical_value_labels(axis, bars, values)

    figure.suptitle(
        "Rating Prediction Error",
        fontsize=17,
        fontweight="bold",
        y=1.01,
    )
    figure.tight_layout()
    return figure


