def build_latent_factor_geometry(
    results: dict[str, dict[str, object]],
) -> matplotlib.figure.Figure | None:
    """Fig 10: 2-D projection of MF and BPR latent factors (t-SNE-like PCA).

    Projects the 50-dim user factors of each model onto the first two
    principal components, showing the two models learn different geometry
    from the same architecture.
    """
    import os
    mf_model_path = PREDICTIONS_DIR / "mf_model.npz"
    bpr_model_path = PREDICTIONS_DIR / "bpr_model.npz"
    if not (mf_model_path.exists() and bpr_model_path.exists()):
        print("  Fig 10 skipped: missing model files.")
        return None
    with np.load(mf_model_path) as z:
        mf_users = z["user_factors"].copy()
    with np.load(bpr_model_path) as z:
        bpr_users = z["user_factors"].copy()
    # Subsample to keep PCA fast (e.g. first 5000 users).
    n = min(5000, mf_users.shape[0])
    figure, axes = plt.subplots(1, 2, figsize=(14, 6))
    for axis, users, label, color in [
        (axes[0], mf_users[:n], "Biased MF", "#0072B2"),
        (axes[1], bpr_users[:n], "BPR-MF", "#984EA3"),
    ]:
        mean = users.mean(axis=0)
        centered = users - mean
        # PCA via SVD (deterministic, no randomness).
        U, S, Vt = np.linalg.svd(centered, full_matrices=False)
        pc1 = centered @ Vt[0]
        pc2 = centered @ Vt[1]
        axis.scatter(pc1, pc2, s=2, color=color, alpha=0.35, marker=".",
                     linewidths=0)
        var_explained = (S ** 2).sum()
        axis.set_xlabel(f"PC1 ({100 * S[0] ** 2 / var_explained:.1f}% var)")
        axis.set_ylabel(f"PC2 ({100 * S[1] ** 2 / var_explained:.1f}% var)")
        axis.set_title(f"{label}: user latent factors (PCA)")
    figure.suptitle(
        "Latent-Factor Geometry: Same Architecture, Different Objectives",
        fontsize=15, fontweight="bold", y=1.02,
    )
    figure.tight_layout()
    return figure


def build_hybrid_score_decomposition(
    results: dict[str, dict[str, object]],
) -> matplotlib.figure.Figure | None:
    """Fig 11: per-row decomposition of the MF+BPR blended z-score.

    For a sample of users, show the blended z-score row as a stacked
    contribution from the MF component (λ·z_MF) and the BPR component
    ((1−λ)·z_BPR). Illustrates that the blend is a convex combination in
    rank space.
    """
    mf = _load_ranking_scores("mf")
    bpr = _load_ranking_scores("bpr")
    if mf is None or bpr is None:
        print("  Fig 11 skipped: missing ranking scores.")
        return None
    meta = json.loads((PREDICTIONS_DIR / "mf_bpr_meta.json").read_text())
    lambda_k = float(meta.get("lambda_ranking", 0.3))
    z_mf = _zscore_rows(mf)
    z_bpr = _zscore_rows(bpr)
    # Show the first 5 users, each as a small panel; 1000 candidates each.
    figure, axes = plt.subplots(5, 1, figsize=(14, 12))
    x = np.arange(mf.shape[1])
    for i, axis in enumerate(axes):
        contrib_mf = lambda_k * z_mf[i]
        contrib_bpr = (1.0 - lambda_k) * z_bpr[i]
        axis.plot(x, contrib_mf, lw=0.8, color="#0072B2",
                  label=f"MF (λ={lambda_k:.1f})")
        axis.plot(x, contrib_bpr, lw=0.8, color="#984EA3",
                  label=f"BPR (1−λ={1 - lambda_k:.1f})")
        axis.plot(x, contrib_mf + contrib_bpr, lw=1.5, color="#E41A1C",
                  label="Blend")
        if i == 0:
            axis.legend(loc="upper right", fontsize=8)
        axis.set_title(f"User {i} (of 5 shown), 1000 candidates", fontsize=10)
        axis.set_xlabel("Candidate position (unsorted)")
        axis.set_ylabel("z-score contribution")
    figure.suptitle(
        "MF+BPR Ranking-Head Score Decomposition (per-row z-blend)",
        fontsize=15, fontweight="bold", y=1.005,
    )
    figure.tight_layout()
    return figure


