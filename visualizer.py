def build_bpr_calibration(
    results: dict[str, dict[str, object]],
) -> matplotlib.figure.Figure | None:
    """Fig 13: BPR raw score vs its post-hoc affine-mapped rating.

    Shows the fitted affine mapping and how much of the [0.5, 5.0] rating
    space is actually reachable. The mapping is degenerate (slope ≈ 0)
    because BPR's validation scores carry no linear rating signal.
    """
    meta = json.loads((PREDICTIONS_DIR / "bpr_meta.json").read_text())
    affine = meta.get("affine_mapping", {})
    slope = float(affine.get("slope", 0.0))
    intercept = float(affine.get("intercept", 0.0))
    bpr = _load_ranking_scores("bpr")
    if bpr is None:
        print("  Fig 13 skipped: missing BPR ranking scores.")
        return None
    # Use the BPR raw scores on the validation rows to show the mapping.
    val = _load_validation_ranking()
    bpr_model_path = PREDICTIONS_DIR / "bpr_model.npz"
    figure, axes = plt.subplots(1, 2, figsize=(14, 5.5))
    # Left: histogram of BPR raw scores + the mapped range.
    scores = bpr.flatten()
    axes[0].hist(scores, bins=60, color="#984EA3", alpha=0.75,
                 edgecolor="white")
    axes[0].set_xlabel("BPR raw score")
    axes[0].set_ylabel("Density")
    mapped_range = [slope * scores.min() + intercept, slope * scores.max() + intercept]
    axes[0].axhline(0, color="k", lw=0.5)
    axes[0].set_title(
        f"BPR raw score distribution\n"
        f"affine map: slope={slope:.3f}, intercept={intercept:.3f}\n"
        f"mapped range ≈ [{min(mapped_range):.2f}, {max(mapped_range):.2f}]"
    )
    # Right: the affine mapping curve over the observed score range, with the
    # valid rating band [0.5, 5.0] shaded.
    s = np.linspace(scores.min(), scores.max(), 200)
    axes[1].plot(s, slope * s + intercept, "-", color="#984EA3", lw=2,
                 label="fitted affine map")
    axes[1].fill_between(s, 0.5, 5.0, color="0.9", alpha=0.5,
                         label="valid rating band [0.5, 5.0]")
    axes[1].set_xlabel("BPR raw score")
    axes[1].set_ylabel("Mapped rating")
    axes[1].set_title("Post-hoc BPR → rating mapping")
    axes[1].legend(fontsize=9)
    figure.suptitle(
        "BPR-MF Rating Calibration (post-hoc affine mapping)",
        fontsize=16, fontweight="bold", y=1.02,
    )
    figure.tight_layout()
    return figure


def generate_all(
    results: dict[str, dict[str, object]],
    output_dir: str | Path,
    output_format: str = "svg",
) -> None:
    """Generate all charts from current-format results."""
    if output_format not in SUPPORTED_FORMATS:
        supported = ", ".join(sorted(SUPPORTED_FORMATS))
        raise ValueError(
            f"Unsupported output format {output_format!r}. "
            f"Choose one of: {supported}."
        )

    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)

    print(
        f"\nGenerating {output_format.upper()} charts in "
        f"{destination}\n"
    )

    chart_specs: list[
        tuple[
            str,
            Callable[
                [dict[str, dict[str, object]]],
                matplotlib.figure.Figure | None,
            ],
        ]
    ] = [
        ("01_rating_errors", build_rating_errors),
        ("02_ranking_metrics", build_ranking_metrics),
        ("03_accuracy_vs_ranking", build_accuracy_vs_ranking),
        ("04_prediction_time", build_prediction_times),
        ("05_out_of_range_predictions", build_out_of_range),
        ("06_training_time", build_training_times),
        ("07_hybrid_rank_distribution", build_hybrid_rank_distribution),
        ("08_hybrid_lambda_sweep", build_hybrid_lambda_sweep),
        ("09_raw_score_scales", build_raw_score_scales),
        ("10_latent_factor_geometry", build_latent_factor_geometry),
        ("11_hybrid_score_decomposition", build_hybrid_score_decomposition),
        ("12_rank_gap_from_models", build_rank_gap_from_models),
        ("13_bpr_calibration", build_bpr_calibration),
    ]

    # Mirror PDFs into the essay's figures directory so ib_cs_ee/figures/*.pdf
    # (referenced by essay.qmd) is regenerated alongside charts/.
    essay_destination = None
    if output_format == "pdf" and ESSAY_FIGURES_DIR.exists():
        essay_destination = ESSAY_FIGURES_DIR

    for filename, builder in chart_specs:
        figure = builder(results)
        if figure is None:
            continue
        # save_figure closes the figure, so save to every destination before
        # closing: always charts/, plus the essay figures dir for PDFs.
        figure_paths = [destination / f"{filename}.{output_format}"]
        if essay_destination is not None:
            figure_paths.append(
                essay_destination / f"{filename}.{output_format}"
            )
        _save_figure_to_all(figure, figure_paths, output_format)

    print(f"\nDone. Charts are in {destination}.")
    if essay_destination is not None:
        print(f"Essay figures updated in {essay_destination}.")


def main() -> None:
    """Load or generate results and create all charts."""
    results_path = (
        Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_RESULTS_DIR
    )
    output_format = sys.argv[2].lower() if len(sys.argv) > 2 else "svg"

    if output_format not in SUPPORTED_FORMATS:
        supported = ", ".join(sorted(SUPPORTED_FORMATS))
        raise SystemExit(
            f"Unsupported format {output_format!r}; use {supported}."
        )

    results = load_results(results_path)

    if not results:
        # The visualizer never generates results itself. If it cannot find
        # current-format algorithm results, it terminates and names the file
        # that is required. Run algorithms.py first to produce it.
        if results_path.is_file():
            raise SystemExit(
                f"No current-format algorithm results found in "
                f"{results_path.name}. Run 'python algorithms.py' to "
                f"generate them, then re-run the visualizer."
            )
        required = (
            results_path / "results.json"
            if results_path.is_dir()
            else results_path
        )
        raise SystemExit(
            f"No algorithm results found. Required file: {required}. "
            f"Run 'python algorithms.py' (then 'python algorithms.py "
            f"--merge') to generate it, then re-run the visualizer."
        )

    generate_all(results, OUTPUT_DIR, output_format)


if __name__ == "__main__":
    main()
