def build_accuracy_vs_ranking(
    results: dict[str, dict[str, object]],
) -> matplotlib.figure.Figure | None:
    """Build a raw RMSE versus NDCG scatter plot."""
    points: list[tuple[str, float, float]] = []
    k = 10

    for name in ordered_algorithms(results):
        rmse = nested_metric(results[name], "rating", "rmse")
        ndcg = nested_metric(results[name], "ranking", "ndcg@k")
        if rmse is None or ndcg is None:
            continue

        points.append((name, rmse, ndcg))

    if len(points) < 2:
        print("  Not enough data for the accuracy-versus-ranking chart.")
        return None

    point_algorithms = [point[0] for point in points]
    k = common_ranking_k(results, point_algorithms)

    figure, axis = plt.subplots(figsize=(12, 8))

    x_values = [point[1] for point in points]
    y_values = [point[2] for point in points]
    x_span = max(x_values) - min(x_values)
    y_span = max(y_values) - min(y_values)

    x_padding = x_span * 0.15 if x_span > 0 else max(x_values[0] * 0.1, 0.1)
    y_padding = y_span * 0.25 if y_span > 0 else 0.05

    axis.set_xlim(min(x_values) - x_padding, max(x_values) + x_padding)
    axis.set_ylim(
        max(0.0, min(y_values) - y_padding),
        max(y_values) + y_padding,
    )

    annotation_offsets = [
        (-36, 18),
        (32, 24),
        (-34, 28),
        (30, -30),
        (-35, -28),
        (34, 20),
        (-32, 20),
        (30, 22),
    ]

    for index, (name, rmse, ndcg) in enumerate(points):
        color = algorithm_color(name)
        axis.scatter(
            rmse,
            ndcg,
            s=350,
            color=color,
            edgecolors="black",
            linewidth=1.2,
            zorder=3,
        )
        axis.annotate(
            algorithm_label(name),
            (rmse, ndcg),
            textcoords="offset points",
            xytext=annotation_offsets[index % len(annotation_offsets)],
            ha="center",
            va="bottom",
            fontsize=11,
            fontweight="bold",
            color=color,
        )

    axis.set_xlabel("Raw RMSE → worse")
    axis.set_ylabel(f"NDCG@{k} ↑ better")
    axis.set_title(
        "Rating Accuracy Versus Ranking Quality\n"
        "Lower RMSE and higher NDCG are preferred"
    )

    axis.text(
        0.98,
        0.96,
        "Pointwise rating accuracy and ranking quality measure "
        "different objectives.",
        transform=axis.transAxes,
        ha="right",
        va="top",
        fontsize=11,
        style="italic",
        bbox={
            "boxstyle": "round,pad=0.5",
            "facecolor": "#FFF9C4",
            "edgecolor": "#F9A825",
            "alpha": 0.9,
        },
    )

    return figure


def build_prediction_times(
    results: dict[str, dict[str, object]],
) -> matplotlib.figure.Figure | None:
    """Build test-set rating prediction-time bars."""
    algorithms = ordered_algorithms(
        results,
        ("timing", "prediction_seconds"),
    )
    if not algorithms:
        print("  No prediction timing data to plot.")
        return None

    algorithms.sort(
        key=lambda name: float(
            nested_metric(results[name], "timing", "prediction_seconds")
        )
    )
    labels = [algorithm_label(name) for name in algorithms]
    values = [
        float(
            nested_metric(results[name], "timing", "prediction_seconds")
        )
        for name in algorithms
    ]
    colors = [algorithm_color(name) for name in algorithms]

    figure, axis = plt.subplots(
        figsize=(11, 0.75 * len(algorithms) + 2)
    )
    bars = axis.barh(
        labels,
        values,
        color=colors,
        edgecolor="white",
        linewidth=0.8,
        height=0.62,
    )
    axis.invert_yaxis()
    axis.set_xlabel("Seconds")
    axis.set_title(
        "Test-Set Rating Prediction Time\n"
        "Includes test-row prediction and ranking-candidate scoring"
    )

    maximum = max(values, default=0.0)
    offset = maximum * 0.02 if maximum > 0 else 0.001
    axis.set_xlim(0, maximum * 1.2 if maximum > 0 else 1)

    for bar, value in zip(bars, values):
        axis.text(
            value + offset,
            bar.get_y() + bar.get_height() / 2,
            f"{value:.3f} s",
            va="center",
            fontsize=10,
            fontweight="bold",
        )

    return figure


